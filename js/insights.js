    function escapeHtml(str) {
        if (str === null || str === undefined) return '';
        return String(str)
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#39;');
    }

    function safeUrl(url) {
        const raw = String(url || '').trim();
        if (!raw) return '#';
        if (/^(https?:\/\/|\/|[a-z0-9_.-]+\.html)/i.test(raw)) return raw;
        return '#';
    }

    function formatDisplayDate(dateStr, fullMonth = false) {
        if (!dateStr) return '';
        const parsed = new Date(dateStr);
        if (isNaN(parsed.getTime())) return String(dateStr);
        return parsed.toLocaleDateString('en-GB', {
            day: 'numeric',
            month: fullMonth ? 'long' : 'short',
            year: 'numeric'
        });
    }

    function estimateReadTime(text) {
        const words = String(text || '').trim().split(/\s+/).filter(Boolean).length;
        const mins = Math.max(3, Math.ceil(words / 180));
        return `${mins} min read`;
    }

    function getStoredInsights() {
        try {
            const raw = localStorage.getItem(INSIGHTS_STORAGE_KEY);
            if (raw) {
                const parsed = JSON.parse(raw);
                if (Array.isArray(parsed) && parsed.length > 0) return parsed;
            }
        } catch (e) {}
        return DEFAULT_INSIGHT_ARTICLES;
    }

    function getPublishedInsights() {
        return getStoredInsights()
            .filter(item => item && item.status !== 'Draft' && item.status !== 'Archived')
            .sort((a, b) => {
                const da = new Date(a.publishedAt || 0).getTime() || 0;
                const db = new Date(b.publishedAt || 0).getTime() || 0;
                return db - da;
            });
    }

    function findInsightArticle(slug, articleId) {
        const stored = getStoredInsights().filter(Boolean);
        const combined = [...stored];
        DEFAULT_INSIGHT_ARTICLES.forEach(def => {
            if (!combined.some(a => String(a.id) === String(def.id) || String(a.slug) === String(def.slug))) {
                combined.push(def);
            }
        });

        const cleanId = String(articleId || '').trim();
        const cleanSlug = String(slug || '').trim().toLowerCase();

        // 1. Exact ID match (highest accuracy when opened from Dashboard Preview)
        if (cleanId) {
            const byId = combined.find(a => String(a.id || '').trim() === cleanId);
            if (byId) return byId;
        }

        // 2. Exact slug match across all stored articles (including Drafts & Published)
        if (cleanSlug) {
            const byExactSlug = combined.find(a => String(a.slug || '').trim().toLowerCase() === cleanSlug);
            if (byExactSlug) return byExactSlug;

            // 3. Match if slug param was actually an article ID
            const byIdFromSlug = combined.find(a => String(a.id || '').trim().toLowerCase() === cleanSlug);
            if (byIdFromSlug) return byIdFromSlug;

            // 4. Prefix / partial slug match (in case slug was truncated)
            const byPrefixSlug = combined.find(a => {
                const s = String(a.slug || '').trim().toLowerCase();
                return s && (s.startsWith(cleanSlug) || cleanSlug.startsWith(s));
            });
            if (byPrefixSlug) return byPrefixSlug;
        }

        return null;
    }

