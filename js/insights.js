    async function syncInsightsFromSupabase() {
        if (!window.IndustraSupabase || typeof window.IndustraSupabase.fetchSiteSetting !== 'function') return;
        try {
            const sbInsights = await window.IndustraSupabase.fetchSiteSetting('insights_articles');
            if (Array.isArray(sbInsights) && sbInsights.length > 0) {
                // Merge local articles (e.g. brand-new Drafts or recent status toggles in the same browser) with Supabase articles
                let localList = [];
                try {
                    const raw = localStorage.getItem(INSIGHTS_STORAGE_KEY);
                    if (raw) {
                        const parsed = JSON.parse(raw);
                        if (Array.isArray(parsed)) localList = parsed;
                    }
                } catch (e) {}

                const params = new URLSearchParams(window.location.search);
                const isDirectPreview = params.get('preview') === '1' || Boolean(params.get('id'));
                const merged = [];
                const seenKeys = new Set();

                const keyOf = (item) => String((item && (item.id || item.slug)) || '').trim().toLowerCase();

                if (isDirectPreview && localList.length > 0) {
                    // When opening a direct preview from Dashboard CRM, prioritize local browser state so unsynced drafts/edits appear immediately
                    localList.forEach(item => {
                        const k = keyOf(item);
                        if (!k || seenKeys.has(k)) return;
                        seenKeys.add(k);
                        merged.push(item);
                    });
                    sbInsights.forEach(item => {
                        const k = keyOf(item);
                        if (!k || seenKeys.has(k)) return;
                        seenKeys.add(k);
                        merged.push(item);
                    });
                } else {
                    // For normal public browsing, take Supabase articles first and append any local-only drafts
                    sbInsights.forEach(item => {
                        const k = keyOf(item);
                        if (!k || seenKeys.has(k)) return;
                        seenKeys.add(k);
                        merged.push(item);
                    });
                    localList.forEach(item => {
                        const k = keyOf(item);
                        if (!k || seenKeys.has(k)) return;
                        seenKeys.add(k);
                        merged.push(item);
                    });
                }

                localStorage.setItem(INSIGHTS_STORAGE_KEY, JSON.stringify(merged));
                routeInsightsPage();
            }
        } catch (e) {
            console.warn('Could not sync insights from Supabase:', e);
        }
    }

